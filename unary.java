public class unary {
    public static void main(String[]args){
        int num=1;
        System.out.println("before unary plus"+num);
        System.out.println("after unary plus"+(+num));
        int m=9;
        System.out.println("before unary minus"+m);
        System.out.println("after unary minus"+(-m));
        double temperature=99.99;
        System.out.println("temperature after unary minus"+(-temperature));
        int n=-9;
        System.out.println("positive number "+(-n));
    }
}
